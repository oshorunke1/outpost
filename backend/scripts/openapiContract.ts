import { readFileSync } from 'node:fs';
import { buildApp } from '../src/app.js';
import { createMemoryAppDeps } from '../src/memoryDeps.js';

export const CONTRACT_HEADER = '# Generated by backend/scripts/export-openapi.ts from the Fastify route schemas. Do not edit by hand.\n';
const FIX = 'Run npx --yes pnpm@10.34.6 --filter @outpost/backend openapi:export and commit it.';

// Builds the app on in-memory fakes, so it needs no database, and returns the YAML to commit.
export async function renderContract(): Promise<string> {
  const app = await buildApp((await createMemoryAppDeps()).deps);
  try {
    await app.ready();
    return CONTRACT_HEADER + app.swagger({ yaml: true });
  } finally {
    await app.close();
  }
}

export interface CheckResult {
  ok: boolean;
  message: string;
}

// A missing file counts as stale, with the same fix-it hint instead of a raw ENOENT.
export function checkContract(target: string, expected: string): CheckResult {
  let committed: string;
  try {
    committed = readFileSync(target, 'utf8');
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return { ok: false, message: `contracts/openapi.yaml is missing. ${FIX}` };
    throw error;
  }
  if (committed !== expected) return { ok: false, message: `contracts/openapi.yaml is stale. ${FIX}` };
  return { ok: true, message: 'contracts/openapi.yaml is current' };
}
